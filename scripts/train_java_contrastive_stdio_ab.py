import copy
import hashlib
import json
from pathlib import Path
import random
import re
import time

import torch

from sagallm.config import ModelConfig
from sagallm.java_behavior import oci_image_ready, run_java_in_oci
from sagallm.java_diverse_corpus import verify_java_diverse_corpus
from sagallm.java_instruction_sft import (
    V016_TOKENIZER_SHA256, encode_row, eval_sample,
    pack, read_split, response_loss, sha_file,
)
from sagallm.java_stdio_curriculum import (
    TRAIN_FAMILIES, VALIDATION_FAMILIES,
    expected_rows, validation_oracle_rows, verify_curriculum,
)
from sagallm.model import SagaTransformer
from sagallm.tokenization import load_tokenizer
from sagallm.training import checkpoint_load, verify_checkpoint_tokenizer
from scripts.train_java_stdio_semantic_sft import (
    PINNED_V018, SEED, STEPS, BATCH, LR, EVAL_AT, SMOKE,
    RESPONSE_LOSS_MIN_DELTA, behavioral_validation, train_schedule,
)

EXPERIMENT = "JAVA_CONTRASTIVE_STDIO_MATCHED_AB_V1"
ARMS = ("control_interleaved", "contrastive_same_variant")
# Fixed pairings, written before model inference. Different algorithms in
# the SAME minibatch, sometimes with the same two-integer stdin contract.
FAMILY_PAIRS = (
    ("stdin_add_offset", "stdin_multiply_offset"),
    ("stdin_max_offset", "stdin_absolute_gap_offset"),
    ("stdin_count_greater", "stdin_even_sum_offset"),
    ("stdin_digit_sum_offset", "stdin_clamp"),
    ("stdin_ascii_upper_suffix", "stdin_ascii_reverse_suffix"),
)
BEHAVIOR_VARIANTS = (2, 3)  # previous experiment executed only (0, 1)
LOSS_ROWS = 24
MAX_ARM_SECONDS = 300


def contrastive_schedule(broad: list[dict], stdio: list[dict],
                         control: list[tuple[tuple[str, int], ...]]
                         ) -> list[tuple[tuple[str, int], ...]]:
    """Only the order/pairing of the same 320 stdin TRAIN samples can change."""
    if (len(control) != STEPS or len(stdio) != len(TRAIN_FAMILIES) * 32
            or len(set(TRAIN_FAMILIES)) != 10
            or set(value for pair in FAMILY_PAIRS for value in pair) != set(TRAIN_FAMILIES)):
        raise ValueError("Invalid frozen contrastive train schedule")
    lookup: dict[tuple[str, int], int] = {}
    for pos, row in enumerate(stdio):
        family = row["family"]
        if family not in TRAIN_FAMILIES:
            raise ValueError("Non-TRAIN family entered contrastive schedule")
        # The id is generated by the sealed, deterministic curriculum.
        prefix = f"train-{family}-"
        if not row["id"].startswith(prefix):
            raise ValueError("Unknown stdin TRAIN id")
        index_text = row["id"][len(prefix):]
        if not re.fullmatch(r"\d{3}", index_text):
            raise ValueError("Malformed stdin parameter variant")
        key = (family, int(index_text))
        if key in lookup:
            raise ValueError("Duplicate prompt/parameter pairing")
        lookup[key] = pos
    all_pairs = [
        (lookup[(left, variant)], lookup[(right, variant)])
        for variant in range(32) for left, right in FAMILY_PAIRS
    ]
    random.Random(SEED + 2).shuffle(all_pairs)
    result = []
    for i, pair in enumerate(all_pairs):
        broad_part = control[i][:2]
        if ([kind for kind, _ in broad_part] != ["broad", "broad"]
                or len(control[i]) != BATCH):
            raise ValueError("Control baseline does not retain two broad rows")
        result.append(broad_part + tuple(("stdio", index) for index in pair))
    return result


def schedule_evidence(control, intervention) -> dict:
    """Prove a pure permutation of identical TRAIN exposures, not new data."""
    if len(control) != STEPS or len(intervention) != STEPS:
        raise ValueError("Invalid A/B schedule lengths")
    def exposures(schedule):
        return {
            group: sorted(index for batch in schedule
                          for kind, index in batch if kind == group)
            for group in ("broad", "stdio")
        }
    base, treatment = exposures(control), exposures(intervention)
    if (base != treatment
            or len(base["broad"]) != STEPS * 2
            or len(base["stdio"]) != STEPS * 2
            or len(set(base["broad"])) != len(base["broad"])
            or len(set(base["stdio"])) != len(base["stdio"])
            or base["stdio"] != list(range(STEPS * 2))):
        raise ValueError("Intervention changes examples or duplicates data")
    return {
        "same_training_examples_both_arms": True,
        "broad_rows_per_arm": len(base["broad"]),
        "stdio_rows_per_arm": len(base["stdio"]),
        "unique_training_exposures": True,
        "same_original_broad_row_positions": all(
            control[i][:2] == intervention[i][:2] for i in range(STEPS)),
        "sole_intervention": "STDIO_TRAIN_ORDER_AND_SAME_INDEX_ALGORITHM_PAIRING",
        "validation_or_test_in_optimizer": False,
    }


def fixed_behavior_only(valid: list[dict]) -> tuple[list[tuple[dict, dict]], list[dict]]:
    """Keep six prospective behavior prompts out of this trial's loss selection."""
    indexed = {record["id"]: record for record in valid}
    oracles = {record["id"]: record for record in validation_oracle_rows()}
    required = []
    for family in VALIDATION_FAMILIES:
        for index in BEHAVIOR_VARIANTS:
            key = f"validation-{family}-{index:03d}"
            if key not in indexed or key not in oracles:
                raise ValueError("Fixed behavior-only validation task excluded")
            row, cases = indexed[key], oracles[key]
            if (row["family"] != cases["family"]
                    or row["family"] != family
                    or len(cases["cases"]) != 3):
                raise ValueError("Validation family/expected outputs changed")
            required.append((row, cases))
    chosen = {r["id"] for r, _ in required}
    selection_rows = [row for row in valid if row["id"] not in chosen]
    if len(required) != 6 or len(selection_rows) < LOSS_ROWS:
        raise ValueError("Insufficient behavior/loss heldback coverage")
    selection_rows = eval_sample(selection_rows, LOSS_ROWS, seed=47)
    if chosen & {row["id"] for row in selection_rows}:
        raise ValueError("Behavior-only examples leaked into checkpoint selection")
    return required, selection_rows


def fit_arm(arm: str, config: ModelConfig, original_model: Path,
            schedule, broad, stdio, selection_rows) -> tuple[dict, dict]:
    if arm not in ARMS or len(schedule) != STEPS:
        raise ValueError("Unregistered training arm")
    torch.manual_seed(SEED)
    model = SagaTransformer(config)
    checkpoint_load(original_model, model)
    model.eval()
    initial_loss = response_loss(model, selection_rows)
    best_loss = initial_loss
    best_step = 0
    best_state = copy.deepcopy(model.state_dict())
    optimizer = torch.optim.AdamW(model.parameters(), lr=LR, weight_decay=0.01)
    steps_done = 0
    history = [{"step": 0, "validation_loss": round(initial_loss, 8)}]
    start = time.monotonic()
    for step, batch_keys in enumerate(schedule, 1):
        if time.monotonic() - start > MAX_ARM_SECONDS:
            raise TimeoutError("Matched A/B CPU training budget exhausted")
        batch = [
            broad[i] if kind == "broad" else stdio[i]
            for kind, i in batch_keys
        ]
        if len(batch) != BATCH:
            raise ValueError("Not four TRAIN examples in minibatch")
        x, y = pack(batch)
        model.train()
        optimizer.zero_grad(set_to_none=True)
        loss = model(x, labels=y).loss
        if not torch.isfinite(loss).item():
            raise FloatingPointError("Nonfinite loss in Java contrastive A/B")
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        optimizer.step()
        steps_done = step
        if step in EVAL_AT:
            model.eval()
            current = response_loss(model, selection_rows)
            history.append({"step": step, "validation_loss": round(current, 8)})
            if current <= best_loss - RESPONSE_LOSS_MIN_DELTA:
                best_state = copy.deepcopy(model.state_dict())
                best_loss, best_step = current, step
    return best_state, {
        "arm": arm, "steps_completed": steps_done,
        "start_validation_loss": round(initial_loss, 8),
        "best_validation_loss": round(best_loss, 8),
        "selected_step": best_step, "history": history,
        "train_seconds": round(time.monotonic() - start, 2),
        "test_split_used": False, "source_programs_executed_on_host": False,
    }


def conditioning_metrics(behavior: dict) -> dict:
    """Use only output SHA values; do not expose source code or runtime output."""
    cases = behavior["cases"]
    if (len(cases) != 6
            or {row["family"] for row in cases} != set(VALIDATION_FAMILIES)):
        raise ValueError("Unexpected behavior diagnostic coverage")
    hashes = [row.get("source_sha256") for row in cases]
    generated = [item for item in hashes if isinstance(item, str)]
    cross = 0
    within = 0
    for i in range(len(cases)):
        for j in range(i+1, len(cases)):
            if hashes[i] and hashes[i] == hashes[j]:
                if cases[i]["family"] == cases[j]["family"]:
                    within += 1
                else:
                    cross += 1
    return {
        "unique_generated_sources": len(set(generated)),
        "six_distinct_prompts": 6,
        "cross_family_identical_source_pairs": cross,
        "within_family_identical_source_pairs": within,
        "source_validity_measured": "SHA256_WITHOUT_EXPOSING_CODE",
        "behavioral_semantics_proven": False,
    }


def selection_gate(base: dict, control: dict, contrastive: dict,
                   diagnostics: dict) -> dict:
    if any(result["unavailable"] for result in (base, control, contrastive)):
        return {"decision": "INCONCLUSIVE_OCI_UNAVAILABLE",
                "improvement_demonstrated": False, "production_adoption": False}
    for item in (base, control, contrastive):
        if item["total_cases"] != 18:
            raise ValueError("Mismatch in validation case count")
    difference = contrastive["cases_passed"] - control["cases_passed"]
    contrast_gain = (difference >= 2
                     and contrastive["cases_passed"] >= base["cases_passed"] + 2
                     and contrastive["tasks_all_pass"] >= control["tasks_all_pass"]
                     and (diagnostics["contrastive_same_variant"]["unique_generated_sources"]
                          > diagnostics["control_interleaved"]["unique_generated_sources"]))
    return {
        "decision": "CONTRASTIVE_VALIDATION_SIGNAL_NOT_DEPLOYED" if contrast_gain
                    else "NO_VALIDATED_CONTRASTIVE_GAIN",
        "contrastive_minus_control_correct_cases": difference,
        "contrastive_minus_base_correct_cases": (
            contrastive["cases_passed"] - base["cases_passed"]),
        "improvement_demonstrated": bool(contrast_gain),
        "production_adoption": False,
        "public_benchmark_used_for_selection": False,
    }


def experiment(base: Path, tokenizer_file: Path, canonical: Path,
               curriculum: Path, output: Path, *, image_id: str,
               allow_oci: bool, acknowledge_vm: bool) -> dict:
    if not allow_oci or not acknowledge_vm:
        raise PermissionError("Explicit OCI opt-in and disposable VM required")
    if not re.fullmatch(r"sha256:[a-f0-9]{64}", image_id):
        raise ValueError("Local pinned OCI image identifier required")
    if output.exists() or output.is_symlink():
        raise FileExistsError("Cannot overwrite existing evidence")
    for path, wanted in (
        (base, PINNED_V018), (tokenizer_file, V016_TOKENIZER_SHA256)
    ):
        if (not path.is_file() or path.is_symlink()
                or path.stat().st_size > 90 * 1024 * 1024
                or sha_file(path) != wanted):
            raise ValueError("Pinned base/tokenizer mismatch")
    verify_java_diverse_corpus(canonical)
    verify_curriculum(curriculum)
    state = torch.load(base, map_location="cpu", weights_only=True)
    verify_checkpoint_tokenizer(state, tokenizer_file)
    cfg = ModelConfig(**state["config"])
    if cfg.max_position_embeddings != 384 or cfg.parameter_count() > 3_000_000:
        raise ValueError("Unexpected checkpoint architecture")
    tokenizer = load_tokenizer(tokenizer_file)
    if tokenizer.vocab_size > cfg.vocab_size:
        raise ValueError("Unmatched vocabulary")
    broad, broad_info = read_split(canonical, "train", tokenizer, 384)
    stdin = [
        encoded for row in expected_rows("train")
        if (encoded := encode_row(row, tokenizer, 384)) is not None
    ]
    valid = [
        encoded for row in expected_rows("validation")
        if (encoded := encode_row(row, tokenizer, 384)) is not None
    ]
    if (len(stdin) != 320 or len(valid) != 36 or
            len(broad) < STEPS * 2 or
            {item["family"] for item in stdin} != set(TRAIN_FAMILIES) or
            {item["family"] for item in valid} != set(VALIDATION_FAMILIES)):
        raise ValueError("Data admission not aligned to pre-registered protocol")
    if {item["family"] for item in broad+stdin} & set(VALIDATION_FAMILIES):
        raise ValueError("Validation family leaked into TRAIN")
    behavior_only, selection_rows = fixed_behavior_only(valid)
    control = train_schedule(broad, stdin)
    contrastive = contrastive_schedule(broad, stdin, control)
    schedule_report = schedule_evidence(control, contrastive)

    if not oci_image_ready("docker", image_id):
        raise RuntimeError("Pinned local Docker JDK image not available")
    smoke = run_java_in_oci(
        SMOKE, "PING\n", backend="docker", image=image_id,
        stdin_data="ping\n", allow_execution=True, timeout=22)
    if smoke["status"] != "PASS":
        raise RuntimeError("Trusted in-OCI stdin/stdout smoke failed before generated Java")

    torch.set_num_threads(2)
    seed_model = SagaTransformer(cfg)
    checkpoint_load(base, seed_model)
    seed_model.eval()
    baseline = behavioral_validation(seed_model, tokenizer, behavior_only, image_id)
    del seed_model
    outcomes = {}
    candidates = {}
    for arm, schedule in zip(ARMS, (control, contrastive)):
        selected_state, stats = fit_arm(
            arm, cfg, base, schedule, broad, stdin, selection_rows)
        model = SagaTransformer(cfg)
        model.load_state_dict(selected_state)
        model.eval()
        behavior = behavioral_validation(model, tokenizer, behavior_only, image_id)
        del model
        outcomes[arm] = {"training": stats, "behavior": behavior}
        candidates[arm] = selected_state

    behavior_by_arm = {"base_v018": baseline}
    behavior_by_arm.update({name: outcomes[name]["behavior"] for name in ARMS})
    diagnostics = {name: conditioning_metrics(report)
                   for name, report in behavior_by_arm.items()}
    gate = selection_gate(
        baseline, outcomes[ARMS[0]]["behavior"],
        outcomes[ARMS[1]]["behavior"], diagnostics)

    output.mkdir(parents=True)
    # The contrastive result is a research candidate, not a deployed model;
    # an original checkpoint config and train provenance are saved explicitly.
    if outcomes[ARMS[1]]["training"]["selected_step"] > 0:
        checkpoint = output / "contrastive-validation-candidate.pt"
        torch.save({
            "model": candidates[ARMS[1]], "config": cfg.to_dict(),
            "experiment": EXPERIMENT, "base_sha256": PINNED_V018,
            "selected_step": outcomes[ARMS[1]]["training"]["selected_step"],
            "is_production_model": False,
        }, checkpoint)
    report = {
        "experiment": EXPERIMENT,
        "status": "MATCHED_AB_CONTRASTIVE_VALIDATION_COMPLETE",
        "prior_diagnostic": "DIFFERENT_TASKS_GENERATED_SAME_SOURCE",
        "origin_checkpoint_sha256": PINNED_V018,
        "tokenizer_sha256": V016_TOKENIZER_SHA256,
        "canonical_train_stats": broad_info,
        "synthetic_stdio_manifest_sha256": sha_file(curriculum / "manifest.json"),
        "stdio_train_rows": len(stdin),
        "validation_examples": len(valid),
        "holdback_behavior_task_ids": [r["id"] for r, _ in behavior_only],
        "holdback_excluded_from_loss_selection": True,
        "loss_selection_rows": len(selection_rows),
        "schedule": schedule_report, "arms": list(ARMS),
        "seed": SEED, "steps_per_arm": STEPS,
        "learning_rate": LR, "batch_size": BATCH,
        "behavior_cases_per_model": 18,
        "baseline_behavior": baseline,
        "arms_results": outcomes,
        "prompt_conditioning_diagnostics": diagnostics,
        "gate": gate,
        "oci_image_id": image_id,
        "oci_smoke": "PASS",
        "model_generated_java_executed": "OCI_ONLY_BEST_EFFORT",
        "generated_java_executed_on_host": False,
        "raw_generated_source_or_stdout_saved": False,
        "original_test_split_accessed": False,
        "public_exercism_data_accessed": False,
        "synthetic_validation_is_independent_benchmark": False,
        "test_split_untouched": True,
        "checkpoint_auto_promoted": False,
        "production_model_unchanged": True,
        "general_java_capability_established": False,
    }
    if (output / "contrastive-validation-candidate.pt").exists():
        report["contrastive_candidate_sha256"] = sha_file(
            output / "contrastive-validation-candidate.pt")
    (output / "ab-report.json").write_text(
        json.dumps(report, indent=2, ensure_ascii=False) + "\n",
        encoding="utf8")
    return report


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--base", type=Path, required=True)
    p.add_argument("--tokenizer", type=Path, required=True)
    p.add_argument("--canonical", type=Path, required=True)
    p.add_argument("--stdio", type=Path, required=True)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--oci-image-id", required=True)
    p.add_argument("--allow-oci", action="store_true")
    p.add_argument("--acknowledge-disposable-vm", action="store_true")
    args = p.parse_args()
    result = experiment(
        args.base, args.tokenizer, args.canonical, args.stdio, args.output,
        image_id=args.oci_image_id, allow_oci=args.allow_oci,
        acknowledge_vm=args.acknowledge_disposable_vm)
    print(json.dumps({
        "status": result["status"],
        "baseline_cases_passed": result["baseline_behavior"]["cases_passed"],
        "arms": {
            name: {
                "selected_step": result["arms_results"][name]["training"]["selected_step"],
                "cases_passed": result["arms_results"][name]["behavior"]["cases_passed"],
                "unique_generated_sources": result["prompt_conditioning_diagnostics"][name]["unique_generated_sources"],
                "cross_family_identical_source_pairs": result["prompt_conditioning_diagnostics"][name]["cross_family_identical_source_pairs"],
            } for name in ARMS
        },
        "gate": result["gate"],
        "model_unchanged": True,
    }, sort_keys=True, ensure_ascii=False))


if __name__ == "__main__":
    main()
