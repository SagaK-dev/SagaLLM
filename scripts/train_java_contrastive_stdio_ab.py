"""Matched Java prompt-conditioning contrastive A/B, validation/OCI only.

Root-cause signal: PR #42 generated the same source for different Java stdin
algorithms. Reorder exactly the SAME 320 existing synthetic TRAIN stdio rows:
control interleaves families, intervention pairs different algorithms on the
same numeric variant inside a minibatch. Both receive the same 320 original
broad TRAIN samples, optimizer steps and identical starting pinned v0.18 weights.

No external/public Exercism material, old test split or model-generated code
is used to train/select weights. Six held-back behavior prompts (variants 2/3)
are excluded even from the loss-selection set in this experiment. They share
family concepts with the existing synthetic validation set and do not prove
independence. All generated Java executes ONLY in disposable VM + OCI.

The outcome is diagnosis, NOT automatic production promotion.
"""
from __future__ import annotations

